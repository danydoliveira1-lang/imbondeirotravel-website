
import { NextResponse } from "next/server";
import { getAuthenticatedAdminEmail } from "../../../../lib/commandCentreAuth";
import { supabaseRequest } from "../../../../lib/supabaseRest";

export const dynamic = "force-dynamic";

const SOURCES = new Set([
  "manual",
  "website",
  "whatsapp",
  "email",
  "telephone",
  "other",
]);

const STATUSES = new Set([
  "new",
  "in_progress",
  "quoted",
  "converted",
  "closed",
]);

const TEXT_FIELDS = [
  "customer_name",
  "customer_email",
  "customer_phone",
  "subject",
  "destination",
  "message",
  "internal_notes",
  "assigned_to",
  "external_message_id",
  "external_thread_id",
];

const OPTIONAL_FIELDS = [
  "customer_id",
  "reservation_id",
  "travel_start_date",
  "travel_end_date",
  "travellers",
  "follow_up_due_at",
  "last_contacted_at",
];

const EDITABLE_FIELDS = new Set([
  ...TEXT_FIELDS,
  ...OPTIONAL_FIELDS,
  "source",
  "status",
]);

function respondError(message, status = 400) {
  return NextResponse.json({ error: message }, { status });
}

function errorResponse(error) {
  console.error("Enquiry API error:", error);

  const message = String(error?.message || "");

  if (message.includes("23505")) {
    return respondError(
      "An enquiry with this external message reference already exists.",
      409
    );
  }

  if (message.includes("23503")) {
    return respondError(
      "The selected customer or reservation is no longer available.",
      409
    );
  }

  return respondError("The enquiry could not be processed.", 500);
}

async function authenticate() {
  return getAuthenticatedAdminEmail();
}

async function findRecord(table, id) {
  const records = await supabaseRequest(table, {
    query: `select=*&id=eq.${encodeURIComponent(id)}&limit=1`,
  });

  return records?.[0] || null;
}

function normaliseInput(input, isCreate) {
  if (
    !input ||
    typeof input !== "object" ||
    Array.isArray(input)
  ) {
    throw new Error("Enter a valid enquiry record.");
  }

  const payload = {};

  for (const [key, value] of Object.entries(input)) {
    if (key === "id" && !isCreate) continue;

    if (key === "id") {
      throw new Error("Enquiry IDs are generated by the server.");
    }

    if (!EDITABLE_FIELDS.has(key)) {
      throw new Error(`Unsupported enquiry field: ${key}`);
    }

    if (TEXT_FIELDS.includes(key)) {
      if (value !== null && typeof value !== "string") {
        throw new Error(`${key} must contain text.`);
      }

      payload[key] = value?.trim() || null;
    } else if (OPTIONAL_FIELDS.includes(key)) {
      payload[key] = value === "" ? null : value;
    } else {
      if (typeof value !== "string") {
        throw new Error(`${key} must contain text.`);
      }

      payload[key] = value.trim().toLowerCase();
    }
  }

  return payload;
}

function validateDate(value, field, dateOnly = false) {
  if (value == null) return;

  if (typeof value !== "string") {
    throw new Error(`${field} must be a valid date.`);
  }

  if (dateOnly && !/^\d{4}-\d{2}-\d{2}$/.test(value)) {
    throw new Error(`${field} must use YYYY-MM-DD.`);
  }

  const parsed = new Date(value);

  if (Number.isNaN(parsed.getTime())) {
    throw new Error(`${field} must be a valid date.`);
  }

  if (
    dateOnly &&
    parsed.toISOString().slice(0, 10) !== value
  ) {
    throw new Error(`${field} must be a real calendar date.`);
  }

  if (!dateOnly) {
    if (!/^\d{4}-\d{2}-\d{2}T.*(?:Z|[+-]\d{2}:\d{2})$/.test(value)) {
      throw new Error(
        `${field} must include a timezone offset.`
      );
    }
  }
}

async function validateEnquiry(payload) {
  if (
    !payload.customer_name ||
    typeof payload.customer_name !== "string"
  ) {
    throw new Error("Customer name is required.");
  }

  if (!SOURCES.has(payload.source)) {
    throw new Error("Choose a valid enquiry source.");
  }

  if (!STATUSES.has(payload.status)) {
    throw new Error("Choose a valid enquiry status.");
  }

  if (
    payload.customer_email &&
    !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(
      payload.customer_email
    )
  ) {
    throw new Error("Enter a valid customer email.");
  }

  if (payload.travellers != null) {
    if (
      !Number.isInteger(payload.travellers) ||
      payload.travellers <= 0
    ) {
      throw new Error(
        "Travellers must be a positive whole number."
      );
    }
  }

  validateDate(
    payload.travel_start_date,
    "Travel start date",
    true
  );

  validateDate(
    payload.travel_end_date,
    "Travel end date",
    true
  );

  validateDate(
    payload.follow_up_due_at,
    "Follow-up date"
  );

  validateDate(
    payload.last_contacted_at,
    "Last contacted date"
  );

  if (
    payload.travel_start_date &&
    payload.travel_end_date &&
    payload.travel_end_date < payload.travel_start_date
  ) {
    throw new Error(
      "Travel end date cannot precede the start date."
    );
  }

  if (payload.customer_id) {
    const customer = await findRecord(
      "customers",
      payload.customer_id
    );

    if (!customer) {
      throw new Error("Selected customer not found.");
    }
  }

  if (payload.reservation_id) {
    const reservation = await findRecord(
      "reservations",
      payload.reservation_id
    );

    if (!reservation) {
      throw new Error("Selected reservation not found.");
    }

    if (
      payload.customer_id &&
      reservation.customer_id &&
      reservation.customer_id !== payload.customer_id
    ) {
      throw new Error(
        "Reservation belongs to a different customer."
      );
    }
  }

  if (
    payload.status === "converted" &&
    !payload.reservation_id
  ) {
    throw new Error(
      "A converted enquiry must link to a reservation."
    );
  }
}

async function recordAudit(
  actorEmail,
  action,
  previousValues,
  savedRecord
) {
  await supabaseRequest("audit_logs", {
    method: "POST",
    body: {
      action,
      section: "enquiries",
      record_id: String(savedRecord.id),
      actor_email: actorEmail,
      previous_values: previousValues,
      new_values: savedRecord,
    },
  });
}

export async function GET(request) {
  const actorEmail = await authenticate();

  if (!actorEmail) {
    return respondError("Unauthorised", 401);
  }

  try {
    const { searchParams } = new URL(request.url);
    const id = searchParams.get("id");

    if (id) {
      const enquiry = await findRecord("enquiries", id);

      if (!enquiry) {
        return respondError("Enquiry not found.", 404);
      }

      return NextResponse.json({ enquiry });
    }

    const enquiries = await supabaseRequest("enquiries", {
      query: "select=*&order=created_at.desc&limit=100",
    });

    return NextResponse.json({
      enquiries: enquiries || [],
    });
  } catch (error) {
    return errorResponse(error);
  }
}

export async function POST(request) {
  const actorEmail = await authenticate();

  if (!actorEmail) {
    return respondError("Unauthorised", 401);
  }

  try {
    const input = await request.json();
    const payload = normaliseInput(input, true);

    payload.source = payload.source || "manual";
    payload.status = payload.status || "new";

    await validateEnquiry(payload);

    const now = new Date().toISOString();

    const record = {
      ...payload,
      id: crypto.randomUUID(),
      created_at: now,
      updated_at: now,
    };

    const result = await supabaseRequest("enquiries", {
      method: "POST",
      body: record,
    });

    const savedRecord = result?.[0];

    if (!savedRecord) {
      throw new Error("Supabase returned no saved enquiry.");
    }

    await recordAudit(
      actorEmail,
      "create",
      null,
      savedRecord
    );

    return NextResponse.json(
      { enquiry: savedRecord },
      { status: 201 }
    );
  } catch (error) {
    if (error instanceof SyntaxError) {
      return respondError("Invalid JSON request.");
    }

    if (
      error.message?.startsWith("Unsupported") ||
      error.message?.startsWith("Enquiry IDs") ||
      !error.message?.startsWith("{")
    ) {
      if (
        !error.message?.includes("Supabase") &&
        !error.message?.includes("fetch") &&
        !error.message?.includes("audit_logs")
      ) {
        const validationMessages = [
          "required",
          "valid",
          "must",
          "cannot",
          "belongs",
          "different",
          "not found",
          "Choose",
          "Enter",
          "Unsupported",
          "Enquiry IDs",
          "converted",
          "timezone",
        ];

        if (
          validationMessages.some(word =>
            error.message?.includes(word)
          )
        ) {
          return respondError(error.message);
        }
      }
    }

    return errorResponse(error);
  }
}

export async function PATCH(request) {
  const actorEmail = await authenticate();

  if (!actorEmail) {
    return respondError("Unauthorised", 401);
  }

  try {
    const input = await request.json();

    if (
      !input ||
      typeof input !== "object" ||
      Array.isArray(input)
    ) {
      return respondError("Invalid enquiry update.");
    }

    const id = String(input.id || "").trim();

    if (!id) {
      return respondError("Enquiry ID is required.");
    }

    const previous = await findRecord("enquiries", id);

    if (!previous) {
      return respondError("Enquiry not found.", 404);
    }

    const changes = normaliseInput(input, false);

    if (!Object.keys(changes).length) {
      return respondError("No changes were supplied.");
    }

    const merged = {
      ...previous,
      ...changes,
    };

    await validateEnquiry(merged);

    const result = await supabaseRequest("enquiries", {
      method: "PATCH",
      query: `id=eq.${encodeURIComponent(id)}`,
      body: {
        ...changes,
        updated_at: new Date().toISOString(),
      },
    });

    const savedRecord = result?.[0];

    if (!savedRecord) {
      throw new Error("Supabase returned no updated enquiry.");
    }

    await recordAudit(
      actorEmail,
      "update",
      previous,
      savedRecord
    );

    return NextResponse.json({ enquiry: savedRecord });
  } catch (error) {
    return errorResponse(error);
  }
}
